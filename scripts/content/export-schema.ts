/*
 * pnpm content:schema — writes supabase/seed-content/content-schema.json, the JSON Schema
 * (draft 2020-12) of one content document {key, kind, schemaVersion, data}, generated from
 * src/lib/content/schema.ts. The editorial backend vendors a copy (config/content-schema.json) and
 * validates drafts with it (ajv's Ajv2020: tuples use prefixItems). Cross-field rules (unique keys,
 * template per path) are runtime-only: see crossFieldProblems() in the schema module.
 *
 *   --check  compare with the file on disk without writing (exit 1 if it is stale)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { CONTENT_SCHEMA_VERSION, ContentDocument } from "@/lib/content/schema";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const FILE = path.join(ROOT, "supabase/seed-content/content-schema.json");

const schema = {
  ...z.toJSONSchema(ContentDocument, { target: "draft-2020-12", io: "input", cycles: "ref", reused: "ref" }),
  $id: "https://www.chinvatbridge.com/schemas/content-document.v1.json",
  title: `Chinvat Bridge content document, schema version ${CONTENT_SCHEMA_VERSION}`,
  description: "Generated by `pnpm content:schema` from src/lib/content/schema.ts. Do not edit by hand.",
};
const json = `${JSON.stringify(schema, null, 2)}\n`;

if (process.argv.includes("--check")) {
  if (!existsSync(FILE) || readFileSync(FILE, "utf8") !== json) {
    console.error(`STALE ${path.relative(ROOT, FILE)}: run pnpm content:schema`);
    process.exit(1);
  }
} else {
  mkdirSync(path.dirname(FILE), { recursive: true });
  writeFileSync(FILE, json);
  console.log(`wrote ${path.relative(ROOT, FILE)}`);
}
