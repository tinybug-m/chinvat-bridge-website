// Builds src/components/brand/mark-geometry.ts from the traced half of the
// mark in docs/brand/newLogo.jpg (1254 px canvas, mirror axis x = 625.5).
// The trace matches the flat half of the artwork at IoU 0.984.
import { writeFileSync } from "node:fs";
import polygonClipping from "polygon-clipping";

const HALF_OUTLINE =
  "M356.5 385 453.5 479 537.5 433 552.5 438 566.5 438 578.5 435 592.5 427 603 416.5 610 403.5 613.5 390 620.5 395 626 396.5 625.5 426 602.5 436 486 498.5 488.5 502 618.5 600 626 603.5 626 639.5 622.5 640 597 658.5 619 683.5 626 688.5 626 722.5 623.5 723 578 766.5 618.5 807 626 811.5 626 846.5 621.5 848 614.5 854 545.5 917 541 907.5 489 731.5 487.5 730 454 751.5 473 780.5 445.5 802 372 712.5 403.5 687 433.5 725 476 696.5 417 627.5 446 600.5 419 508.5 324 416.5Z M498.5 546 505 555.5 574.5 635 595 621.5 582.5 610Z M467.5 556 468 562.5 490 639.5 502 680.5 504.5 683 550 651.5Z M571.5 676 520 711.5 554.5 745 557.5 744 599 705.5Z M534.5 768 537 781.5 560.5 858 596 828.5Z";
const RING = { cx: 559.5, cy: 384.2, outer: 53.5, inner: 23.2 };
const MIRROR_X = 1251; // x' = 1251 - x reflects about the axis at 625.5
const CIRCLE_SEGMENTS = 128;

function parseRings(d) {
  return d
    .split("Z")
    .map((part) => part.replace("M", "").trim())
    .filter(Boolean)
    .map((part) => {
      const n = part.split(/[\s,]+/).map(Number);
      const ring = [];
      for (let i = 0; i < n.length; i += 2) ring.push([n[i], n[i + 1]]);
      ring.push(ring[0]);
      return ring;
    });
}

function circle(cx, cy, r) {
  const ring = [];
  for (let i = 0; i < CIRCLE_SEGMENTS; i++) {
    const a = (i / CIRCLE_SEGMENTS) * Math.PI * 2;
    ring.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]);
  }
  ring.push(ring[0]);
  return ring;
}

const outline = parseRings(HALF_OUTLINE);
const annulus = [circle(RING.cx, RING.cy, RING.outer), circle(RING.cx, RING.cy, RING.inner).reverse()];
const left = polygonClipping.union([outline], [annulus]);
const right = left.map((polygon) => polygon.map((ring) => ring.map(([x, y]) => [MIRROR_X - x, y])));
const full = polygonClipping.union(left, right);

const round = (v) => Math.round(v * 10) / 10;
const toPath = (multi) =>
  multi
    .map((polygon) =>
      polygon
        .map((ring) => "M" + ring.slice(0, -1).map(([x, y]) => `${round(x)} ${round(y)}`).join(" ") + "Z")
        .join(""),
    )
    .join("");
const toRings = (multi) => multi.map((polygon) => polygon.map((ring) => ring.slice(0, -1).map(([x, y]) => [round(x), round(y)])));

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const polygon of full) for (const ring of polygon) for (const [x, y] of ring) {
  minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
}

const out = `// Generated by scripts/build-mark.mjs from the traced brand mark. Do not edit by hand.

/** Mark bounds in source pixels; the mirror axis is x = ${(MIRROR_X / 2).toFixed(1)}. */
export const MARK_BOUNDS = { minX: ${round(minX)}, minY: ${round(minY)}, maxX: ${round(maxX)}, maxY: ${round(maxY)} } as const;
export const MARK_AXIS_X = ${MIRROR_X / 2};

/** Left (flat) half including its ring node, as an even-odd SVG path. */
export const MARK_LEFT_PATH = "${toPath(left)}";

/** Right (material) half: the left half mirrored about the axis. */
export const MARK_RIGHT_PATH = "${toPath(right)}";

/** Both halves welded into one outline with holes, for extrusion. Each polygon is [outer, ...holes]. */
export const MARK_POLYGONS: ReadonlyArray<ReadonlyArray<ReadonlyArray<readonly [number, number]>>> = ${JSON.stringify(toRings(full))};
`;
writeFileSync(new URL("../src/components/brand/mark-geometry.ts", import.meta.url), out);
console.log(`left polygons ${left.length}, full polygons ${full.length}, rings ${full.map((p) => p.length).join(",")}, bounds ${round(minX)},${round(minY)} → ${round(maxX)},${round(maxY)}`);
